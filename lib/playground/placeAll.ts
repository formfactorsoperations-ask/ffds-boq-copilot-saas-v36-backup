/*
  Every line that draws, put on the plan in its room.

  Options generated by the setup wizard (the standard templates, or the AI) and
  lines that were in a BOQ before its rooms were on the plan come with no
  places: the BOQ Playground lists them under Needs a place. This places them
  one after another, each in its own room (placeInRoom: on a free wall, or the
  open floor), so the plan shows the furniture. A line whose room is not on the
  plan, or has no space left, keeps waiting; a line that does not draw
  (painting, wallpaper) stays in its room's list. Lines already placed are not
  moved.
*/
import type { BoqItem, Item, Room } from '../../types';
import { placeInRoom } from './excel';
import { needsPlace } from './board';

export interface PlacedAll {
  boq: BoqItem[];
  /** Lines put on the plan. */
  placed: number;
  /** Lines that draw but found no room on the plan, or no space in it. */
  waiting: number;
}

export function placeWaitingLines(boq: BoqItem[], rooms: Room[], bankMap: Map<string, Item>): PlacedAll {
  const todo = new Set(needsPlace(boq, bankMap).map(l => String(l.id)));
  if (!todo.size || !rooms.some(r => r.plan)) return { boq, placed: 0, waiting: todo.size };
  const out = [...boq];
  let placed = 0, waiting = 0;
  out.forEach((line, i) => {
    if (!todo.has(String(line.id))) return;
    const r = placeInRoom(line, rooms, out, bankMap);
    if (r.lands === 'plan') { out[i] = r.line; placed++; } else if (r.lands === 'waits') waiting++;
  });
  return { boq: placed ? out : boq, placed, waiting };
}

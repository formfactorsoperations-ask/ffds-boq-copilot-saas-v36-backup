interface TierManagerProps {
    tiers: ProposalTier[];
    setTiers: React.Dispatch<React.SetStateAction<ProposalTier[]>>;
    activeTierId: string | null;
    setActiveTierId: (id: string | null) => void;
    projectContext: ProjectContext;
    setProjectContext: React.Dispatch<React.SetStateAction<ProjectContext>>;
    bank?: Item[];
    setActiveTab: (tab: string) => void;
    onImportClick?: () => void;
    projects?: FullProjectData[];
    /** This project's id, so it is not benchmarked against itself. */
    projectId?: string;
    /** The studio's own typology templates. Falls back to the built-ins. */
    templates?: TemplateData;
    /** Opens an option's BOQ over this screen (App's BOQ slide-over), at these lines when given. */
    onEditBoq?: (tierId: string, focusLineIds?: string[]) => void;
}

const TierManager: React.FC<TierManagerProps> = ({ tiers, setTiers, activeTierId, setActiveTierId, projectContext, setProjectContext, bank, setActiveTab, onImportClick, projects, projectId, templates, onEditBoq }) => {
    /* Signed scope: the version the client signed changes only through a
       Scope Revision, so it cannot be synced, re-approved or deleted here. */
    const scopeFlowOn = isScopeFlowOn(projectContext);
    const signedTierId = lockedTierId(projectContext);
    const { currentUserAuth, currentRole } = useOrg() as any;
    const approverName = currentUserAuth?.displayName || currentUserAuth?.email || currentRole || 'Studio';
    const [editingTierId, setEditingTierId] = useState<string | null>(null);
    const [editingTierName, setEditingTierName] = useState('');
    const [revertOpen, setRevertOpen] = useState(false);
    const [marginShiftAmount, setMarginShiftAmount] = useState<number>(0);
    /* Hide figures (lib/figuresPrivacy): Tune margin shows margins, so it closes while they are hidden. */
    const marginsHidden = useFiguresHidden();

    /*
      Regenerate the options from the project as it stands now.

      The generator is a pure function of the context — rooms, site state, civil
      scope, templates, the bank — but its output is a snapshot taken at one
      moment. Every time any of those inputs changes, or the generator itself
      is corrected, the existing options are stale and the only way to refresh
      them was to walk the whole setup wizard again.

      It replaces, it does not merge: options generated by two different
      versions of the rules sitting side by side is worse than either.
    */
    const [regenOpen, setRegenOpen] = useState(false);

    const regenPreview = useMemo(() => {
        const rooms = realRooms(projectContext.rooms);
        return {
            rooms: rooms.length,
            area: Math.round(rooms.reduce((sum, r) => sum + (r.size || 0), 0)) || projectContext.area || 0,
            scope: describeCivilScope(resolveCivilScope(projectContext)),
            discarding: tiers.length,
            lines: tiers.reduce((sum, t) => sum + (t.boq?.length || 0), 0),
        };
    }, [projectContext, tiers]);

    /*
      An approved tier is the commercial baseline — what the client was shown
      and what the payment schedule and revision chain hang off. Regenerating
      over it would silently move the contract, so it is refused rather than
      warned about.
    */
    const approvedTier = tiers.find(t => t.id === projectContext.approvedTierId);

    /* What Regenerate replaced, so one click can put it back. */
    const [regenUndo, setRegenUndo] = useState<{ tiers: ProposalTier[]; activeTierId: string | null; approvedTierId?: string } | null>(null);

    const handleRegenerate = () => {
        const fresh = generateStandardPackages(
            projectContext,
            bank || [],
            templates || INITIAL_TEMPLATES,
            projectContext.proposalMode || 'tiered',
        );
        if (!fresh.length) {
            showSuccessWithNext('Nothing to generate — check the rooms and configuration.');
            setRegenOpen(false);
            return;
        }
        setRegenUndo({ tiers, activeTierId, approvedTierId: projectContext.approvedTierId });
        setTiers(fresh);
        setActiveTierId((fresh.find(t => t.name === 'Comfort Upgrade') || fresh[0]).id);
        setProjectContext(prev => ({ ...prev, approvedTierId: undefined }));
        setRegenOpen(false);
    };

    /* The offer lapses: undoing much later would also throw away edits made since. */
    React.useEffect(() => {
        if (!regenUndo) return;
        const t = setTimeout(() => setRegenUndo(null), 20000);
        return () => clearTimeout(t);
    }, [regenUndo]);

    const handleUndoRegenerate = () => {
        if (!regenUndo) return;
        setTiers(regenUndo.tiers);
        setActiveTierId(regenUndo.activeTierId);
        setProjectContext(prev => ({ ...prev, approvedTierId: regenUndo.approvedTierId }));
        setRegenUndo(null);
    };

    const activeTier = tiers.find(t => t.id === activeTierId) || tiers[0];

    /*
      One column per option, its versions inside it (lib/optionChains). A
      column shows the selected version when it is one of its own, else the
      version last picked in it, else the newest.
    */
    const chains = useMemo(() => optionChains(tiers), [tiers]);
    const versionCount = tiers.length;
    const [picked, setPicked] = useState<Record<string, string>>({});
    const columns: GridColumn[] = useMemo(() => chains.map(chain => {
        const tier = chain.versions.find(v => v.id === activeTier?.id) || shownVersion(chain, picked[chain.root.id]);
        return { chain, tier, latest: tier.id === latestOf(chain).id, prev: previousVersion(chain, tier) };
    }), [chains, activeTier?.id, picked]);

    /* Once the client has signed, the options they did not choose fold to one line each. */
    const [showNotChosen, setShowNotChosen] = useState(false);
    const signedChain = scopeFlowOn && signedTierId ? chainOf(chains, signedTierId) : undefined;
    const visibleColumns = signedChain && !showNotChosen ? columns.filter(c => c.chain === signedChain) : columns;
    const notChosen = signedChain ? columns.filter(c => c.chain !== signedChain).map(c => c.tier) : [];

    const handlePickVersion = (tierId: string) => {
        const chain = chainOf(chains, tierId);
        if (chain) setPicked(prev => ({ ...prev, [chain.root.id]: tierId }));
        setActiveTierId(tierId);
    };

    /* What separates the options on screen (lib/tierComparison.ts), priced line
       for line as the tier summary is, so its totals reconcile with the columns. */
    const comparison = useMemo(
        () => compareTiers(visibleColumns.map(c => c.tier), buildBankMap(bank || [], projectContext?.adHocItems)),
        [visibleColumns, bank, projectContext?.adHocItems],
    );

    /* Tune margin: the old Systematic Margin Adjuster, now opened from an option's ⋯ menu. */
    const [tuneOpen, setTuneOpen] = useState(false);

    const displayValue = activeTier ? (activeTier.summary.totalRevenue || activeTier.summary.totalSell) : 0;

    const bankMap = useMemo(() => {
        const map = new Map<string, Item>((bank || []).map(i => [i.id, i]));
        if (projectContext?.adHocItems) {
            projectContext.adHocItems.forEach(i => map.set(i.id, i));
        }
        return map;
    }, [bank, projectContext?.adHocItems]);

    const activeTierCost = useMemo(() => {
        if (!activeTier) return 0;
        return activeTier.summary.totalCost || 0;
    }, [activeTier, displayValue]);

    const simulatedSellValue = useMemo(() => {
        if (!activeTier) return 0;
        if (marginShiftAmount === 0) return activeTier.summary.totalSell;
        
        let simulatedSell = 0;
        (activeTier.boq || []).forEach(b => {
            const bankItem = bankMap.get(b.bankId);
            const currentMargin = b.marginOverride ?? bankItem?.margin ?? 20;
            const newMargin = Math.max(0, Math.min(80, currentMargin + marginShiftAmount));
            const effectiveMaterials = b.baseRate !== undefined ? b.baseRate : (bankItem?.materials || 0);
            const effectiveLabor = b.labor !== undefined ? b.labor : (bankItem?.labor || 0);
            const sell = calculateSellPrice(effectiveMaterials, effectiveLabor, newMargin) * b.qty;
            
            /* As actuals are paid to the vendor directly, so they are not in FFDS's total. */
            if (b.boqStatus !== 'deleted' && b.boqStatus !== 'substituted' && b.boqStatus !== 'excluded' && b.boqStatus !== 'client_procured' && !isAsActuals(b, bankItem?.name)) {
                simulatedSell += sell;
            }
        });
        return simulatedSell;
    }, [activeTier, marginShiftAmount, bankMap]);

    /* A percentage fee is charged on the as-actuals as well, which a margin shift does not move. */
    const simulatedDesignFee = useMemo(
        () => designFeeFor(projectContext, simulatedSellValue, activeTier?.summary.asActualsTotal || 0),
        [projectContext, simulatedSellValue, activeTier]);

    const simulatedTotalRevenue = simulatedSellValue + simulatedDesignFee;

    const simulatedBlendedGm = useMemo(() => {
        if (simulatedTotalRevenue === 0) return 0;
        const simulatedProfit = (simulatedSellValue - activeTierCost) + simulatedDesignFee;
        return (simulatedProfit / simulatedTotalRevenue) * 100;
    }, [simulatedTotalRevenue, simulatedSellValue, activeTierCost, simulatedDesignFee]);

    const handleApplyMarginShift = () => {
        if (!activeTier) return;
        
        let newTotalCost = 0;
        let newTotalSell = 0;
        let newAsActuals = 0;
        let activeItemCount = 0;

        // Systematic shift updates the margin override of each item
        const updatedBoq = activeTier.boq.map(b => {
            const bankItem = bankMap.get(b.bankId);
            const currentMargin = b.marginOverride ?? bankItem?.margin ?? 20;
            const newMargin = Math.max(0, Math.min(80, currentMargin + marginShiftAmount));
            const effectiveMaterials = b.baseRate !== undefined ? b.baseRate : (bankItem?.materials || 0);
            const effectiveLabor = b.labor !== undefined ? b.labor : (bankItem?.labor || 0);
            const cost = (effectiveMaterials + effectiveLabor) * b.qty;
            const sell = calculateSellPrice(effectiveMaterials, effectiveLabor, newMargin) * b.qty;

            if (b.boqStatus !== 'deleted' && b.boqStatus !== 'substituted' && b.boqStatus !== 'excluded' && b.boqStatus !== 'client_procured') {
                activeItemCount++;
                if (isAsActuals(b, bankItem?.name)) newAsActuals += sell;
                else { newTotalCost += cost; newTotalSell += sell; }
            }

            return {
                ...b,
                marginOverride: Number(newMargin.toFixed(2))
            };
        });

        // Design Fee Calc: a percentage is charged on the as-actuals too.
        const newDesignFee = designFeeFor(projectContext, newTotalSell, newAsActuals);

        const newTotalRevenue = newTotalSell + newDesignFee;
        const newBlendedGm = newTotalRevenue > 0 ? (((newTotalSell - newTotalCost) + newDesignFee) / newTotalRevenue) * 100 : 0;
        const newTotalGm = newTotalSell > 0 ? ((newTotalSell - newTotalCost) / newTotalSell) * 100 : 0;

        // Update the tiers list
        setTiers(prev => prev.map(t => {
            if (t.id !== activeTier.id) return t;
            return {
                ...t,
                boq: updatedBoq,
                summary: {
                    ...t.summary,
                    totalSell: newTotalSell,
                    totalCost: newTotalCost,
                    totalGm: newTotalGm,
                    itemCount: activeItemCount,
                    totalRevenue: newTotalRevenue,
                    designFee: newDesignFee,
                    blendedGm: newBlendedGm,
                    asActualsTotal: newAsActuals,
                }
            };
        }));

        // If this tier is the approved / active baseline tier or current contract, sync projectContext financials
        const isApproved = projectContext.approvedTierId === activeTier.id || activeTier.lifecycleTag === 'Current contract';
        setProjectContext(prev => {
            const prevFinancials = prev.financials || {
                initiationFeePaid: 0,
                billablePercent: 100,
                executionGstEnabled: true,
                projectedCashValue: 0,
                taxLimitYearly: 2000000,
                goodwillDiscount: 0,
                discounts: [],
                paymentRevisions: [],
            };
            
            const updatedFinancials = {
                ...prevFinancials,
                approvedExecutionValue: isApproved || !prevFinancials.approvedExecutionValue ? newTotalSell : prevFinancials.approvedExecutionValue,
                approvedDesignValue: isApproved || !prevFinancials.approvedDesignValue ? newDesignFee : prevFinancials.approvedDesignValue,
            };

            const updatedEngagement = prev.engagement ? {
                ...prev.engagement,
                executionValue: isApproved ? newTotalSell : prev.engagement.executionValue,
                designFee: isApproved ? newDesignFee : prev.engagement.designFee,
            } : prev.engagement;

            return {
                ...prev,
                financials: updatedFinancials,
                engagement: updatedEngagement
            };
        });

        setMarginShiftAmount(0); // Reset
        showSuccessWithNext(`Successfully applied systematic margin shift to all items in ${activeTier.name}. Updated Execution Sell: ${formatCurrency(newTotalSell)}.`);
    };


    /* The studio's own projects, never invented ones (lib/tierBenchmarks.ts). */
    const benchmarks = useMemo(
        () => otherBenchmarks(projects, { id: projectId, name: projectId ? undefined : projectContext.name }),
        [projects, projectId, projectContext.name],
    );
    const studioMedianGm = useMemo(() => medianGm(benchmarks), [benchmarks]);
    const comparableProjects = useMemo(
        () => closestInSize(benchmarks, projectContext.area || 0),
        [benchmarks, projectContext.area],
    );

    const handleAddTier = () => {
        const newTier: ProposalTier = {
            id: id(),
            name: `New Option ${tiers.length + 1}`,
            timestamp: Date.now(),
            boq: [],
            projectContext,
            summary: { totalSell: 0, totalCost: 0, totalGm: 0, itemCount: 0, totalRevenue: 0, designFee: 0, blendedGm: 0 },
            lifecycleTag: 'Draft'
        };
        setTiers(prev => [...prev, newTier]);
        setActiveTierId(newTier.id);
    };
    
    /* A deep copy of an option, as a new draft, carrying its material spec edits (lib/specOverrides.ts). */
    const draftCopyOf = (src: ProposalTier, patch: Partial<ProposalTier>): ProposalTier => {
        const copy: ProposalTier = {
            ...JSON.parse(JSON.stringify(src)),
            id: id(),
            timestamp: Date.now(),
            lifecycleTag: 'Draft',
            ...patch,
        };
        delete (copy as any).approval;
        return copy;
    };

    /*
      The client asked for changes: the option's next version, in the same
      column. The one it came from is kept as it was, so the studio can still
      see what the client was shown.
    */
    const handleNewVersion = (tierId: string): string | undefined => {
        const src = tiers.find(t => t.id === tierId);
        if (!src) return undefined;
        const copy = draftCopyOf(src, { parentTierId: src.id, name: src.name });
        setTiers(prev => [...prev, copy]);
        setProjectContext(prev => contextWithTierCopied(prev, src, copy.id));
        setActiveTierId(copy.id);
        const chain = chainOf(chains, src.id);
        const n = chain ? chain.versions.length + 1 : 2;
        showSuccessWithNext(`v${n} of ${src.name} is ready to edit. v${n - 1} is kept as it was.`);
        return copy.id;
    };

    /* A separate package that starts from this one: a column of its own, with this option's built-in specs. */
    const handleCopyAsOption = (tierId: string) => {
        const src = tiers.find(t => t.id === tierId);
        if (!src) return;
        const keptSpecs = src.specsFrom || builtInSpecsName(src, tiers);
        const copy = draftCopyOf(src, { name: `${src.name} (Copy)`, ...(keptSpecs ? { specsFrom: keptSpecs } : {}) });
        delete (copy as any).parentTierId;
        setTiers(prev => [...prev, copy]);
        setProjectContext(prev => contextWithTierCopied(prev, src, copy.id));
        setActiveTierId(copy.id);
    };

    /* A version that was really meant as another package: it moves to a column of its own. */
    const handleOwnOption = (tierId: string) => {
        setTiers(prev => prev.map(t => {
            if (t.id !== tierId) return t;
            const keptSpecs = builtInSpecsName(t, prev);
            const { parentTierId, ...rest } = t;
            return { ...rest, ...(keptSpecs && !t.specsFrom ? { specsFrom: keptSpecs } : {}) };
        }));
        setActiveTierId(tierId);
    };

    /*
      Its copies stay. They used to keep pointing at the deleted option, so the
      rail — which shows options with no parent and the children of those —
      showed them nowhere, though they were still in the proposal. They now
      hang off the deleted option's own parent, or become options of their own,
      and keep the built-in specs they had through it (lib/comparison.ts).
    */
    const handleDeleteTier = (tierId: string) => {
        const deleted = tiers.find(t => t.id === tierId);
        const keptSpecs = deleted ? builtInSpecsName(deleted, tiers) : undefined;
        setTiers(prev => prev.filter(t => t.id !== tierId).map(t => {
            if (t.parentTierId !== tierId) return t;
            const { parentTierId, ...rest } = t;
            return {
                ...rest,
                ...(deleted?.parentTierId ? { parentTierId: deleted.parentTierId } : {}),
                ...(keptSpecs && !t.specsFrom ? { specsFrom: keptSpecs } : {}),
            };
        }));
        if (projectContext.approvedTierId === tierId) {
            setProjectContext(prev => ({...prev, approvedTierId: undefined}));
        }
        if (activeTierId === tierId) {
            // A deleted version hands over to the one it was made from, in the same column.
            const remainingTiers = tiers.filter(t => t.id !== tierId);
            const back = deleted?.parentTierId && remainingTiers.find(t => t.id === deleted.parentTierId);
            setActiveTierId(back ? back.id : remainingTiers.length > 0 ? remainingTiers[0].id : null);
        }
    };
    
    const handleStartEditing = (tier: ProposalTier) => {
        setEditingTierId(tier.id);
        setEditingTierName(tier.name);
    }
    
    /* A blank name is not saved: the option keeps the one it had. Its
       material specs and the studio's edits to them follow it (lib/specOverrides.ts). */
    const handleSaveEdit = () => {
        if (!editingTierId) return;
        const name = editingTierName.trim();
        const tier = tiers.find(t => t.id === editingTierId);
        if (name && tier && name !== tier.name) {
            const oldName = tier.name;
            setTiers(prev => prev.map(t => t.id === tier.id ? { ...t, name, originalName: t.originalName ?? oldName } : t));
            setProjectContext(prev => contextWithTierRenamed(prev, tier.id, oldName));
        }
        setEditingTierId(null);
    }

    const handleNameKey = (e: React.KeyboardEvent<HTMLInputElement>) => {
        if (e.key === 'Enter') handleSaveEdit();
        if (e.key === 'Escape') setEditingTierId(null);
    }

    /*
      Edit BOQ opens the option's BOQ over this screen. An approved version is
      frozen: editing it makes the next version first, and that is what opens.
      The signed scope opens as it is; the editor keeps it read-only.
    */
    const handleEditBoq = (tierId: string) => {
        const approvedDraft = projectContext.approvedTierId === tierId && tierId !== signedTierId;
        const target = approvedDraft ? handleNewVersion(tierId) || tierId : tierId;
        setActiveTierId(target);
        if (onEditBoq) onEditBoq(target);
        else setActiveTab('boq-editor');
    };

    /*
      A line in "Where the money goes" opens the BOQ Editor at that line. A
      draft or a signed option opens straight away (opening changes nothing; a
      signed BOQ is read-only there). An approved option asks first, because
      editing it makes the next version, as Edit BOQ does.
    */
    const [openLinesAsk, setOpenLinesAsk] = useState<{ tierId: string; lineIds: string[] } | null>(null);
    const openBoqAt = (tierId: string, lineIds: string[]) => {
        setActiveTierId(tierId);
        if (onEditBoq) onEditBoq(tierId, lineIds);
        else setActiveTab('boq-editor');
    };
    const handleOpenLines = (tierId: string, lineIds: string[]) => {
        if (projectContext.approvedTierId === tierId && tierId !== signedTierId) setOpenLinesAsk({ tierId, lineIds });
        else openBoqAt(tierId, lineIds);
    };
    const confirmOpenLines = () => {
        if (!openLinesAsk) return;
        /* A version is a deep copy, so its lines keep their ids and the editor finds them. */
        const target = handleNewVersion(openLinesAsk.tierId) || openLinesAsk.tierId;
        setOpenLinesAsk(null);
        openBoqAt(target, openLinesAsk.lineIds);
    };
    const askTier = openLinesAsk ? tiers.find(t => t.id === openLinesAsk.tierId) : undefined;
    const askChain = askTier ? chainOf(chains, askTier.id) : undefined;
    const askNext = askChain ? askChain.versions.length + 1 : 2;

    /* Approve and Sync are one rule (lib/tierApproval.ts): the replaced
       contract is snapshotted, and the approval records who and when. */
    const makeBaseline = (tier: ProposalTier) => {
        const now = Date.now();
        const previousApprovedId = projectContext.approvedTierId;
        setProjectContext(prev => contextWithApproved(prev, tier, tiers, now));
        setTiers(prev => tiersWithApproved(prev, tier.id, previousApprovedId, { at: now, by: approverName }));
    };

    const handleSyncTier = (tierId: string) => {
        const tier = tiers.find(t => t.id === tierId);
        if (!tier) return;
        makeBaseline(tier);
        setActiveTierId(tier.id);
        showSuccessWithNext(`Synced ${tier.name} to Revision Studio and Payment Schedule as the approved baseline.`);
    };

    const handleApproveTier = (tierId: string) => {
        const selectedTier = tiers.find(t => t.id === tierId);
        if (!selectedTier) return;
        makeBaseline(selectedTier);
        showSuccessWithNext('Option set as current contract');
    }

    /* Undo an approval (lib/tierApproval.ts): the option goes back to a draft,
       and the contract it replaced, if there was one, is the baseline again. */
    const revertTo = useMemo(() => {
        const back = previousBaseline(projectContext, tiers);
        return back ? tiers.find(t => t.id === back.tierId) || null : null;
    }, [projectContext, tiers]);

    const handleRevertApproval = () => {
        const revertedId = projectContext.approvedTierId;
        if (!revertedId || revertedId === signedTierId) return;
        const reverted = tiers.find(t => t.id === revertedId);
        setProjectContext(prev => contextWithoutApproved(prev, tiers));
        setTiers(prev => tiersWithoutApproved(prev, revertedId, revertTo?.id));
        setRevertOpen(false);
        showSuccessWithNext(revertTo
            ? `${reverted?.name || 'The option'} is a draft again. ${revertTo.name} is the approved baseline.`
            : `${reverted?.name || 'The option'} is a draft again. Nothing is approved.`);
    }

    React.useEffect(() => { setRevertOpen(false); }, [activeTierId]);

    const contractTimeline = useMemo(() => {
        const points: {
            id: string;
            stage: string;
            amount: number;
            date: string;
            gm: number;
            delta?: number;
        }[] = [];

        const snapshots = projectContext.financials?.paymentSnapshots || [];
        if (snapshots.length > 0) {
            snapshots.forEach((snap, idx) => {
                const amount = (snap.approvedExecutionValue || 0) + (snap.approvedDesignValue || 0);
                const prevAmount = idx > 0 ? (snapshots[idx - 1].approvedExecutionValue || 0) + (snapshots[idx - 1].approvedDesignValue || 0) : null;
                const dateStr = snap.timestamp ? new Date(snap.timestamp).toLocaleDateString('en-GB', { day: '2-digit', month: 'short', year: 'numeric' }) : 'Initial';
                const isBooking = idx === 0 || snap.tierName.toLowerCase().includes('booking') || snap.tierName.toLowerCase().includes('contract');
                
                // Find matching tier for exact GM if possible
                const matchingTier = tiers.find(t => t.id === snap.tierId);
                const gm = matchingTier?.summary?.blendedGm ?? matchingTier?.summary?.totalGm ?? 0;

                points.push({
                    id: snap.tierId || `snap-${idx}`,
                    stage: isBooking ? 'Approved while booking' : (snap.tierName.toLowerCase().includes('annexure') || snap.tierName.toLowerCase().includes('revision') ? 'Revised after design' : snap.tierName),
                    amount: amount,
                    date: dateStr,
                    gm: gm,
                    delta: prevAmount !== null ? amount - prevAmount : undefined
                });
            });
        } else {
            /*
              Derived from the booking tier — but only if there is one.

              This used to fall through to `tiers[0]`, so a project where
              nothing had ever been approved still printed "Approved while
              booking ₹12,62,151" with a green dot, directly beneath a banner
              correctly saying "This is a draft version. Approve it to freeze
              the scope." The first option a studio happens to create is not a
              contract, and a panel that invents one is worse than an empty
              panel: it is the number everyone downstream quotes.

              An approval is now something the project records — an
              `approvedTierId`, or a lifecycle tag the approval flow wrote —
              never the accident of array order.
            */
            const bookingTier =
                tiers.find(t => t.lifecycleTag === 'Approved while booking' || t.lifecycleTag === 'Current contract')
                || (projectContext.approvedTierId ? tiers.find(t => t.id === projectContext.approvedTierId) : null)
                // A version's parent is not a booking: the version it was made from was never approved by being copied.
                || null;

            if (bookingTier) {
                const bookingAmount = bookingTier.summary.totalRevenue || bookingTier.summary.totalSell || 0;
                const bookingDate = bookingTier.timestamp ? new Date(bookingTier.timestamp).toLocaleDateString('en-GB', { day: '2-digit', month: 'short', year: 'numeric' }) : '12 Jun 2026';
                const bookingGm = bookingTier.summary.blendedGm ?? 0;

                points.push({
                    id: bookingTier.id,
                    stage: 'Approved while booking',
                    amount: bookingAmount,
                    date: bookingDate,
                    gm: bookingGm
                });

                // If activeTier is an annexure or revision or distinct child tier
                if (activeTier && activeTier.id !== bookingTier.id) {
                    const activeAmount = activeTier.summary.totalRevenue || activeTier.summary.totalSell || 0;
                    const activeDate = activeTier.timestamp ? new Date(activeTier.timestamp).toLocaleDateString('en-GB', { day: '2-digit', month: 'short', year: 'numeric' }) : '22 Jul 2026';
                    const activeGm = activeTier.summary.blendedGm ?? 0;
                    const delta = activeAmount - bookingAmount;

                    points.push({
                        id: activeTier.id,
                        stage: activeTier.lifecycleTag === 'Revised after design' ? 'Revised after design' : (activeTier.name.toLowerCase().includes('revision') || activeTier.name.toLowerCase().includes('annexure') ? 'Revised after design' : activeTier.name),
                        amount: activeAmount,
                        date: activeDate,
                        gm: activeGm,
                        delta: delta
                    });
                }
            }
        }

        return points;
    }, [projectContext.financials?.paymentSnapshots, tiers, activeTier]);

    const totalContractDelta = useMemo(() => {
        if (contractTimeline.length <= 1) return 0;
        return contractTimeline[contractTimeline.length - 1].amount - contractTimeline[0].amount;
    }, [contractTimeline]);

    if (!activeTier) return <div>Loading...</div>;

    return (
        <div className="w-full max-w-[1400px] mx-auto flex flex-col gap-4 font-sans pb-12">
            <PricingGrid
                columns={visibleColumns}
                summary={`${chains.length} ${chains.length === 1 ? 'option' : 'options'}${versionCount > chains.length ? ` · ${versionCount} versions` : ''}`}
                toolbar={<>
                    <button type="button" onClick={handleAddTier}
                        className="group w-full inline-flex items-center justify-center gap-1.5 px-3 py-2 rounded-xl bg-[#3D52A0] text-white text-sm font-bold hover:bg-[#334486]">
                        <Plus className="w-4 h-4 transition-transform duration-300 group-hover:rotate-90" /> Add option
                    </button>
                    <button type="button" onClick={() => setRegenOpen(true)} title="Rebuild all options from the current brief, rooms and civil scope"
                        className="group w-full inline-flex items-center justify-center gap-1.5 px-3 py-2 rounded-xl border border-slate-300 bg-white text-slate-700 text-sm font-bold hover:bg-slate-50">
                        <RefreshCw className="w-4 h-4 text-slate-400 transition-transform duration-500 group-hover:rotate-180" /> Regenerate
                    </button>
                </>}
                notChosen={notChosen}
                showNotChosen={showNotChosen}
                onToggleNotChosen={() => setShowNotChosen(v => !v)}
                allTiers={tiers}
                bank={bank || []}
                projectContext={projectContext}
                activeTierId={activeTier.id}
                specLabel={comparison.specLabel}
                comparison={comparison}
                studioMedianGm={studioMedianGm}
                benchmarksCount={benchmarks.length}
                signedTierId={signedTierId}
                scopeFlowOn={scopeFlowOn}
                revertOpen={revertOpen}
                revertToName={revertTo?.name || null}
                describeApproval={describeApproval}
                canDelete={(tid) => tid !== signedTierId}
                renaming={{ id: editingTierId, value: editingTierName, onChange: setEditingTierName, onSave: handleSaveEdit, onKey: handleNameKey }}
                comparables={<>
                    <p className="text-[10px] font-bold uppercase tracking-wider text-slate-500 mb-2 flex items-center gap-1.5"><Building2 className="w-3.5 h-3.5" /> Comparable past projects · closest in size</p>
                    {comparableProjects.length === 0 ? (
                        <p className="text-xs text-slate-500">No other priced projects yet. This fills in as the studio quotes more.</p>
                    ) : (
                        <ul className="divide-y divide-slate-100 rounded-xl border border-slate-200">
                            {comparableProjects.map((p, idx) => {
                                const raw = (activeTier.summary.blendedGm ?? 0) - p.gm;
                                const diffPct = Math.abs(raw) < 0.05 ? 0 : raw;
                                return (
                                    <li key={p.id || idx} className="px-4 py-2.5 flex items-center justify-between gap-3 hud-row-in" style={{ animationDelay: `${idx * 30}ms` }}>
                                        <span className="min-w-0">
                                            <span className="block text-sm font-semibold text-slate-800">{p.name}</span>
                                            <span className="block text-[11px] text-slate-500">{formatCurrency(p.value)} · {p.itemsCount} items</span>
                                        </span>
                                        <span className="text-right">
                                            <span className="block text-sm font-black text-slate-800 tabular-nums">{p.gm.toFixed(1)}%</span>
                                            <span className={`block text-[11px] font-semibold tabular-nums ${diffPct > 0 ? 'text-[#3D52A0]' : diffPct < 0 ? 'text-rose-700' : 'text-slate-400'}`}>
                                                {diffPct > 0 ? `+${diffPct.toFixed(1)}` : diffPct.toFixed(1)} pts vs {activeTier.name}
                                            </span>
                                        </span>
                                    </li>
                                );
                            })}
                        </ul>
                    )}
                </>}
                hasHistory={contractTimeline.length > 0}
                history={<>
                    <p className="text-[10px] font-bold uppercase tracking-wider text-slate-500 mb-2 flex items-center gap-1.5"><LineChart className="w-3.5 h-3.5" /> Contract value over time</p>
                    {contractTimeline.length === 0 && <p className="text-xs text-slate-500">Nothing approved yet. Approve an option to set the booking value; every revision is then tracked against it.</p>}
                    {contractTimeline.length > 0 && (
                        <ul className="divide-y divide-slate-100 rounded-xl border border-slate-200">
                            {contractTimeline.map((point, idx) => (
                                <li key={point.id || idx} className="px-4 py-2.5 flex items-center justify-between gap-3 hud-row-in" style={{ animationDelay: `${idx * 30}ms` }}>
                                    <span className="min-w-0">
                                        <span className="block text-xs font-semibold text-slate-800">{point.stage}</span>
                                        <span className="block text-[11px] text-slate-500">{point.date} · {point.gm.toFixed(1)}% GM</span>
                                    </span>
                                    <span className="text-right">
                                        <span className="block text-sm font-black text-slate-800 tabular-nums">{formatCurrency(point.amount)}</span>
                                        {point.delta !== undefined && point.delta !== 0 && (
                                            <span className={`block text-[11px] font-semibold tabular-nums ${point.delta > 0 ? 'text-amber-700' : 'text-emerald-700'}`}>
                                                {point.delta > 0 ? `+${formatCurrency(point.delta)}` : `-${formatCurrency(Math.abs(point.delta))}`}
                                            </span>
                                        )}
                                    </span>
                                </li>
                            ))}
                            {contractTimeline.length > 1 && (
                                <li className="px-4 py-2.5 flex items-center justify-between text-xs text-slate-500">
                                    <span>Booking → today</span>
                                    <span className={`font-bold tabular-nums ${totalContractDelta > 0 ? 'text-amber-700' : totalContractDelta < 0 ? 'text-emerald-700' : 'text-slate-700'}`}>
                                        {totalContractDelta > 0 ? `+${formatCurrency(totalContractDelta)}` : totalContractDelta < 0 ? `-${formatCurrency(Math.abs(totalContractDelta))}` : '₹0'}
                                    </span>
                                </li>
                            )}
                        </ul>
                    )}
                </>}
                actions={{
                    select: (tid) => setActiveTierId(tid),
                    pickVersion: handlePickVersion,
                    editBoq: handleEditBoq,
                    openLines: handleOpenLines,
                    newVersion: (tid) => { handleNewVersion(tid); },
                    copyAsOption: handleCopyAsOption,
                    ownOption: handleOwnOption,
                    startRename: (tid) => { const t = tiers.find(x => x.id === tid); if (t) handleStartEditing(t); },
                    importBoq: onImportClick,
                    remove: handleDeleteTier,
                    approve: handleApproveTier,
                    askRevert: () => setRevertOpen(true),
                    keepApproval: () => setRevertOpen(false),
                    revert: handleRevertApproval,
                    sync: handleSyncTier,
                    tuneMargin: (tid) => { setActiveTierId(tid); setMarginShiftAmount(0); setTuneOpen(true); },
                    startRevision: () => setActiveTab('revision-studio'),
                    offers: (tid) => { setActiveTierId(tid); setActiveTab('analytics'); },
                    saveDiscounts: (next) => setProjectContext(prev => ({ ...prev, financials: { ...(prev.financials as any), discounts: next } })),
                }}
            />

            {/* Tune margin: the old Systematic Margin Adjuster, for the option it was opened on. */}
            {tuneOpen && !marginsHidden && createPortal(
                <div className="fixed inset-0 z-[300] flex items-center justify-center p-4 no-print" role="dialog" aria-label={`Tune margin: ${activeTier.name}`}>
                    <div className="phd-scrim absolute inset-0 bg-[#12182F]/40 backdrop-blur-sm" onClick={() => setTuneOpen(false)} />
                    <div className="phd-pop relative w-full max-w-lg bg-white rounded-3xl border border-slate-200 shadow-2xl overflow-hidden">
                        <div className="px-6 pt-5 pb-4">
                            <p className="text-[10px] font-extrabold uppercase tracking-[0.14em] text-[#3D52A0]">Tune margin</p>
                            <h2 className="font-bold text-slate-800">{activeTier.name}</h2>
                            <p className="text-xs text-slate-500 mt-0.5">Moves every line's margin by the same number of points, within 0% and 80%.</p>
                        </div>
                        <div className="px-6 pb-5 space-y-4">
                            <div className="flex items-center gap-4">
                                <input type="range" min="-10" max="10" step="0.5" value={marginShiftAmount} aria-label="Margin shift in points"
                                    onChange={(e) => setMarginShiftAmount(parseFloat(e.target.value))}
                                    className="flex-1 h-1.5 bg-slate-200 rounded-lg appearance-none cursor-pointer accent-[#3D52A0]" />
                                <span className={`text-base font-black w-20 text-right tabular-nums ${marginShiftAmount > 0 ? 'text-[#3D52A0]' : marginShiftAmount < 0 ? 'text-rose-700' : 'text-slate-800'}`}>
                                    {marginShiftAmount > 0 ? `+${marginShiftAmount.toFixed(1)}` : marginShiftAmount.toFixed(1)} pts
                                </span>
                            </div>
                            <div className="grid grid-cols-2 gap-3">
                                {[
                                    ['Work', formatCurrency(simulatedSellValue)],
                                    ['Design fee', formatCurrency(simulatedDesignFee)],
                                    ['Total', formatCurrency(simulatedTotalRevenue)],
                                    ['Blended GM', `${simulatedBlendedGm.toFixed(1)}%`],
                                ].map(([k, v]) => (
                                    <div key={k} className="rounded-xl border border-slate-200 px-3 py-2">
                                        <p className="text-[10px] font-bold uppercase tracking-wider text-slate-500">{k}</p>
                                        <p className="text-sm font-black text-slate-800 tabular-nums">{v}</p>
                                    </div>
                                ))}
                            </div>
                        </div>
                        <div className="px-6 py-4 bg-slate-50 border-t border-slate-100 flex justify-end gap-2">
                            <button type="button" onClick={() => setTuneOpen(false)} className="px-4 py-2 rounded-xl border border-slate-300 bg-white text-slate-700 text-sm font-bold hover:bg-slate-50">Cancel</button>
                            <button type="button" disabled={marginShiftAmount === 0} onClick={() => { handleApplyMarginShift(); setTuneOpen(false); }}
                                className="px-4 py-2 rounded-xl bg-[#3D52A0] text-white text-sm font-bold hover:bg-[#334486] disabled:opacity-50">Apply to every line</button>
                        </div>
                    </div>
                </div>,
                document.body,
            )}
            {/* A line clicked on an approved option: editing it makes the next version. */}
            {openLinesAsk && askTier && createPortal(
                <div className="fixed inset-0 z-[300] flex items-center justify-center p-4 no-print" role="dialog" aria-label={`Open ${askTier.name} in the BOQ Editor`}>
                    <div className="phd-scrim absolute inset-0 bg-[#12182F]/40 backdrop-blur-sm" onClick={() => setOpenLinesAsk(null)} />
                    <div className="phd-pop relative w-full max-w-md bg-white rounded-3xl border border-slate-200 shadow-2xl overflow-hidden">
                        <div className="px-6 pt-5 pb-4">
                            <p className="text-[10px] font-extrabold uppercase tracking-[0.14em] text-[#3D52A0]">Open in the BOQ Editor</p>
                            <h2 className="font-bold text-slate-800">{askTier.name} is approved</h2>
                            <p className="text-xs text-slate-500 mt-1 leading-relaxed">
                                Editing it makes v{askNext}. v{askNext - 1} stays as approved, at the figure the client was shown.
                            </p>
                        </div>
                        <div className="px-6 py-4 bg-slate-50 border-t border-slate-100 flex justify-end gap-2">
                            <button type="button" onClick={() => setOpenLinesAsk(null)} className="px-4 py-2 rounded-xl border border-slate-300 bg-white text-slate-700 text-sm font-bold hover:bg-slate-50">Cancel</button>
                            <button type="button" onClick={confirmOpenLines} className="px-4 py-2 rounded-xl bg-[#3D52A0] text-white text-sm font-bold hover:bg-[#334486]">Open v{askNext}</button>
                        </div>
                    </div>
                </div>,
                document.body,
            )}
            {/*
                Regenerate.

                It names what it will build FROM and what it will discard,
                because those are the two facts that decide whether pressing it
                is safe — a brief that has moved on is the reason to, and three
                hand-edited options are the reason to hesitate.
            */}
            {regenUndo && (
                <div role="status" className="fixed bottom-6 left-1/2 -translate-x-1/2 z-[60] flex items-center gap-4 rounded-xl bg-slate-900 text-white px-4 py-2.5 shadow-2xl hud-row-in no-print">
                    <span className="text-sm font-semibold">Regenerated {tiers.length} options from the current brief</span>
                    <button onClick={handleUndoRegenerate} className="text-sm font-bold underline underline-offset-2 hover:text-slate-200">Undo</button>
                    <button onClick={() => setRegenUndo(null)} aria-label="Dismiss" className="text-slate-400 hover:text-white text-sm font-bold">✕</button>
                </div>
            )}

            {regenOpen && (
                <div className="fixed inset-0 z-[220] bg-[#3D52A0]/90 backdrop-blur-md flex items-center justify-center p-5 no-print"
                    onClick={() => setRegenOpen(false)}>
                    <div className="bg-white rounded-2xl w-full max-w-md p-6 shadow-2xl" onClick={e => e.stopPropagation()}>
                        <h3 className="text-lg font-bold text-slate-900 flex items-center gap-2 mb-2">
                            <SparklesIcon className="w-5 h-5 text-indigo-600" /> Regenerate options
                        </h3>

                        {approvedTier ? (
                            <>
                                <p className="text-xs text-slate-500 mb-3 leading-relaxed">
                                    <b className="text-slate-800">{approvedTier.name}</b> is the approved baseline — the figure the
                                    client was shown, and what the payment schedule and revision chain hang off. Regenerating would
                                    move the contract without anyone deciding to.
                                </p>
                                <p className="text-[11px] text-slate-500 leading-relaxed mb-4">
                                    Un-approve it first if the scope really has changed, or raise a revision instead.
                                </p>
                                <div className="flex justify-end">
                                    <button onClick={() => setRegenOpen(false)}
                                        className="px-4 py-2 bg-white border border-slate-200 text-slate-600 rounded-xl text-xs font-bold hover:bg-slate-50 transition-colors">
                                        Close
                                    </button>
                                </div>
                            </>
                        ) : (
                            <>
                                <p className="text-xs text-slate-500 mb-3 leading-relaxed">
                                    Rebuilds every option from the project as it stands now.
                                </p>
                                {/* What it builds from — the four inputs that decide
                                    every quantity in the result. */}
                                <div className="bg-slate-50 border border-slate-200 rounded-xl p-3 mb-3 space-y-1.5">
                                    {[
                                        ['Rooms', `${regenPreview.rooms} rooms · ${regenPreview.area.toLocaleString('en-IN')} sq ft`],
                                        ['Configuration', projectContext.config || 'not set'],
                                        ['Site state', (projectContext.propertyStatus || 'finished').replace(/_/g, ' ')],
                                        ['Civil scope', regenPreview.scope],
                                    ].map(([k, v]) => (
                                        <div key={k} className="flex gap-3 text-xs">
                                            <span className="w-24 shrink-0 text-slate-400 font-semibold">{k}</span>
                                            <span className="text-slate-800 font-medium">{v}</span>
                                        </div>
                                    ))}
                                </div>
                                {regenPreview.discarding > 0 && (
                                    <div className="bg-amber-50 border border-amber-100 rounded-xl p-3 mb-4">
                                        <p className="text-xs text-amber-900 font-semibold">
                                            Replaces {regenPreview.discarding} existing {regenPreview.discarding === 1 ? 'option' : 'options'}
                                            {regenPreview.lines > 0 ? ` and ${regenPreview.lines} priced lines` : ''}
                                        </p>
                                        <p className="text-[11px] text-amber-800/80 mt-1 leading-relaxed">
                                            Hand-edited quantities, margins and added items in them are replaced. Options built by
                                            two different versions of the rules cannot sit side by side and mean anything. You can
                                            undo this straight after.
                                        </p>
                                    </div>
                                )}
                                <div className="flex justify-end gap-2">
                                    <button onClick={() => setRegenOpen(false)}
                                        className="px-4 py-2 bg-white border border-slate-200 text-slate-600 rounded-xl text-xs font-bold hover:bg-slate-50 transition-colors">
                                        Cancel
                                    </button>
                                    <button onClick={handleRegenerate}
                                        className="px-4 py-2 bg-indigo-600 text-white rounded-xl text-xs font-bold hover:bg-indigo-700 shadow-sm transition-colors">
                                        {regenPreview.discarding > 0 ? 'Regenerate and replace' : 'Regenerate'}
                                    </button>
                                </div>
                            </>
                        )}
                    </div>
                </div>
            )}
        </div>
    );
};

export default TierManager;
